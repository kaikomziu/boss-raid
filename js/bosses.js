import { BASE_HP, HP_GROWTH } from './config.js';

// 生き物と絵文字をペアにして名前と見た目を一致させる
const CREATURES = [
  ['ゴブリンロード', '👺'], ['デーモン', '👿'], ['ドラゴン', '🐉'], ['クラーケン', '🦑'],
  ['リッチ', '💀'], ['ベヒーモス', '🦣'], ['ワーウルフ', '🐺'], ['ミノタウロス', '🐗'],
  ['ヒュドラ', '🐍'], ['ゴーレム', '🗿'], ['ワイバーン', '🦖'], ['レヴィアタン', '🐋'],
  ['ケルベロス', '🐕'], ['グリフォン', '🦅'], ['マンティコア', '🦁'], ['オーガ', '👹'],
  ['ゾンビキング', '🧟'], ['ヴァンパイア', '🧛'], ['サンドワーム', '🪱'], ['メガクラブ', '🦀'],
  ['キングコング', '🦍'], ['ホワイトシャーク', '🦈'], ['タランチュラ', '🕷️'], ['スコーピオン', '🦂'],
  ['メガロドン', '🦕'], ['フェニックス', '🦤'], ['バット', '🦇'], ['サタン', '😈'],
  ['エイリアン', '👽'], ['ロボット', '🤖'],
];
const PREFIX = [
  '暴虐の', '深淵の', '烈火の', '氷結の', '雷鳴の', '猛毒の', '腐敗の', '虚無の',
  '黄金の', '漆黒の', '灼熱の', '極寒の', '嵐の', '大地の', '幻影の', '狂気の',
  '不滅の', '古の', '真紅の', '蒼き', '断罪の', '混沌の', '天災級の', '終末の',
];
const HUES = [0, 22, 42, 130, 158, 195, 218, 262, 288, 322];

// 32bit ハッシュ(index -> 疑似乱数)
function h(n) {
  let x = (n + 1) * 2654435761;
  x = (x ^ (x >>> 15)) * 2246822519;
  x = (x ^ (x >>> 13)) * 3266489917;
  return (x ^ (x >>> 16)) >>> 0;
}

export function bossFor(index) {
  if (index === 0) {
    return { index: 0, emoji: '🟢', name: 'スライム大王', hue: 135, maxHp: BASE_HP };
  }
  const [base, emoji] = CREATURES[h(index) % CREATURES.length];
  const name = PREFIX[h(index * 7 + 2) % PREFIX.length] + base;
  const hue = HUES[h(index * 3 + 1) % HUES.length];
  const maxHp = Math.floor(BASE_HP * Math.pow(HP_GROWTH, index));
  return { index, emoji, name, hue, maxHp };
}
